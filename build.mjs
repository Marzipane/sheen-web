// Builds dist/ from tokens/tokens.json and src/: node build.mjs [--check]
// - dist/sheen.css      tokens as CSS custom properties + every stylesheet in src/css, in name order
// - dist/sheen.min.css  the same without comments and spare whitespace
// - dist/sheen.js       src/js/sheen.js (and .min.js)
// With --check, nothing is written: it fails when dist/ is out of date (CI runs this).
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';

const tokens = JSON.parse(readFileSync('tokens/tokens.json', 'utf8'));
const kebab = (s) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());
const colorVars = (set) => Object.entries(set).map(([k, v]) => `--sheen-${kebab(k)}:${v};`).join('');
const numVars = (group, set) => Object.entries(set).map(([k, v]) => `--sheen-${group}-${k}:${v}px;`).join('');

const tokenCss = `/* sheen-web tokens, generated from tokens/tokens.json (Flutter sheen ${tokens.flutterVersion}) */
:root{${colorVars(tokens.color.light)}${numVars('space', tokens.space)}${numVars('radius', tokens.radius)}${numVars('width', tokens.width)}color-scheme:light}
@media (prefers-color-scheme: dark){:root:not([data-theme="light"]){${colorVars(tokens.color.dark)}color-scheme:dark}}
:root[data-theme="dark"]{${colorVars(tokens.color.dark)}color-scheme:dark}
:root[data-theme="light"]{${colorVars(tokens.color.light)}color-scheme:light}
`;

const parts = readdirSync('src/css').filter((f) => f.endsWith('.css')).sort();
const css = tokenCss + parts.map((f) => `/* ${f} */\n` + readFileSync('src/css/' + f, 'utf8')).join('\n');
const minCss = css.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\s+/g, ' ').replace(/\s*([{};,>])\s*/g, '$1').replace(/:\s+/g, ':').replace(/;}/g, '}').trim();
const js = readFileSync('src/js/sheen.js', 'utf8');
const minJs = js.replace(/^\s*\/\/.*$/gm, '').replace(/\n\s*\n/g, '\n').trim();

// icons: the Flutter sheen glyphs (icons/stroke, icons/filled, copied from Marzipane/sheen tool/icons) as a PHP map
const inner = (svg) => svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
const iconMap = (dir) => readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()
  .map((f) => `    '${f.slice(0, -4)}' => '${inner(readFileSync(dir + '/' + f, 'utf8')).replace(/'/g, "\\'")}',`).join('\n');
const iconsPhp = `<?php\n\n// GENERATED by build.mjs from icons/ (the Flutter sheen glyphs). Do not edit by hand.\n\nreturn [\n  'stroke' => [\n${iconMap('icons/stroke')}\n  ],\n  'filled' => [\n${iconMap('icons/filled')}\n  ],\n];\n`;

// icons for pages without Laravel: one SVG sprite, <svg><use href="sheen-icons.svg#sheen-play-fill"/></svg>
const symbols = (dir, suffix) => readdirSync(dir).filter((f) => f.endsWith('.svg')).sort().map((f) => {
  const svg = readFileSync(dir + '/' + f, 'utf8');
  const attrs = (svg.match(/<svg([^>]*)>/) || ['', ''])[1].replace(/\s*xmlns="[^"]*"/, '').trim();
  return `<symbol id="sheen-${f.slice(0, -4)}${suffix}" ${attrs}>${inner(svg)}</symbol>`;
}).join('');
const sprite = `<svg xmlns="http://www.w3.org/2000/svg">${symbols('icons/stroke', '')}${symbols('icons/filled', '-fill')}</svg>\n`;

const out = { 'dist/sheen.css': css, 'dist/sheen-icons.svg': sprite, 'dist/sheen.min.css': minCss + '\n', 'dist/sheen.js': js, 'dist/sheen.min.js': minJs + '\n', 'resources/icons.php': iconsPhp };
if (process.argv.includes('--check')) {
  const stale = Object.entries(out).filter(([p, s]) => !existsSync(p) || readFileSync(p, 'utf8') !== s).map(([p]) => p);
  if (stale.length) {
    console.error('dist/ is out of date, run node build.mjs: ' + stale.join(', '));
    process.exit(1);
  }
  console.log('dist/ is up to date');
} else {
  for (const [p, s] of Object.entries(out)) writeFileSync(p, s);
  console.log('built ' + Object.keys(out).join(', ') + ` (${(minCss.length / 1024).toFixed(1)} kB css min)`);
}
